"""Form a grade test from a vacancy description.

TZ section 2: a single shared item bank leaks, and an LLM item per candidate is not comparable.
The grade test stays parametric. What changes per vacancy is the topic mix: named skills pull the
blueprint toward the families that measure those skills, and the specialization plan fills the rest.
Sample items are generated by the same families the candidate will see. The right answer is not returned.
"""
