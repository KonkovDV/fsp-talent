@dataclass(frozen=True)
class Phrasing:
    stem: str
    right: str
    wrong: tuple[str, str, str]


@dataclass(frozen=True)
class Idea:
    spec: str
    slug: str
    level: int
    phrasings: tuple[Phrasing, ...]

    @property
    def id(self) -> str:
        return f"{self.spec}:{self.slug}"


def wording_key(idea: Idea, index: int) -> str:
    return f"{idea.id}:{index}"


def idea_id(key: str) -> str | None:
    """``backend:n-plus-one:1`` → ``backend:n-plus-one``. A parametric family key has no idea."""
    spec, _, tail = key.partition(":")
    slug, sep, n = tail.rpartition(":")
    if sep and slug and n.isdigit() and spec:
        return f"{spec}:{slug}"
    return None


def _p(stem: str, right: str, a: str, b: str, c: str) -> Phrasing:
    return Phrasing(stem, right, (a, b, c))


def _idea(spec: str, level: int, slug: str, rows: list[Phrasing]) -> Idea:
    return Idea(spec, slug, level, tuple(rows))


def _http(level: int, slug: str, right: str, wrong: tuple[str, str, str], stems: tuple[str, str, str]) -> Idea:
    return Idea("http", slug, level, tuple(_p(stem, right, *wrong) for stem in stems))


