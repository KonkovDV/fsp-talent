def bank_ideas(spec: str | None = None) -> list[Idea]:
    if spec is None:
        return list(_BANK_ROWS)
    return [idea for idea in _BANK_ROWS if idea.spec == spec]


def http_ideas() -> list[Idea]:
    return list(_HTTP)


def has_bank(spec: str, level: int) -> bool:
    return any(idea.level == level for idea in _BANK_ROWS if idea.spec == spec)


def _render(rng: random.Random, idea: Idea, index: int) -> Item:
    phrasing = idea.phrasings[index]
    options, correct = options_with(rng, phrasing.right, list(phrasing.wrong))
    return Item(
        stem=phrasing.stem, options=options, correct=correct,
        explanation="Вопрос на понимание; в разборе после теста верный вариант не показывается.",
        static_key=wording_key(idea, index),
    )


def _pick(rng: random.Random, ideas: list[Idea], level: int, avoid: set[str], used_ideas: set[str]) -> Item | None:
    fresh: list[tuple[Idea, list[int]]] = []
    for idea in ideas:
        if idea.level != level or idea.id in used_ideas:
            continue
        indexes = [i for i in range(len(idea.phrasings)) if wording_key(idea, i) not in avoid]
        if indexes:
            fresh.append((idea, indexes))
    if not fresh:
        return None
    idea, indexes = fresh[rng.randrange(len(fresh))]
    return _render(rng, idea, indexes[rng.randrange(len(indexes))])


def pick_bank(rng: random.Random, level: int, spec: str,
              avoid: set[str] | None = None, used_ideas: set[str] | None = None) -> Item | None:
    return _pick(rng, bank_ideas(spec), level, avoid or set(), used_ideas or set())


def pick_http(rng: random.Random, level: int, avoid: set[str] | None = None,
              used_ideas: set[str] | None = None) -> Item | None:
    return _pick(rng, _HTTP, level, avoid or set(), used_ideas or set())


def draw_attempt(rng: random.Random, spec: str, level: int, history: set[str], slots: int, *,
                 http: bool) -> list[str]:
    """What one attempt shows if it spends ``slots`` concept questions at this level, bank first."""
    avoid = set(history)
    used: set[str] = set()
    keys: list[str] = []
    for _ in range(slots):
        item = pick_bank(rng, level, spec, avoid, used)
        if item is None and http:
            item = pick_http(rng, level, avoid, used)
        if item is None or item.static_key is None:
            break
        keys.append(item.static_key)
        avoid.add(item.static_key)
        found = idea_id(item.static_key)
        if found:
            used.add(found)
    return keys


def overlap(first: list[str], second: list[str]) -> float:
    """Share of the second attempt that the candidate has already seen."""
    if not second:
        return 0.0
    return len(set(first) & set(second)) / len(second)
